//  13 枚标记的静态几何数据。与 AgentLogo.swift 里手绘的矩形组（PixelMark）不同，
//  这些标记的轮廓线更碎，用几何路径表达比用矩形逼近更准，因此这里存 SVG path 的
//  `d` 数据，由 AgentMarkView 用 SwiftUI Canvas + CoreGraphics 渲染成单色标记。
//
//  坐标口径：`viewBox` 一律取「字形自己的包围盒」，与 AgentLogo 里 PixelMark 的口径一致
//  （那里的 bounds 就是各部分矩形的并集，目的正是抵消不同标记在原始画布里的留白差异）。
//  渲染时按 min(宽比, 高比) 等比缩放并居中，视图高度恒为调用方给的 size、宽度按 viewBox
//  宽高比推导，因此各标记在同一 size 下视觉高度一致。
//  官方 SVG 的路径坐标逐点取自官方数据，只是整体平移到字形包围盒原点：gemini 官方
//  28×28 本来就满幅；cursor 官方 512×512 里字形只占 332×378、factory 508×508 里只占
//  317×310，照原画布缩放会让这两枚在同一 size 下只有别人的六到七成高。
//
//  真源与取证：
//  · gemini / cursor / factory 取官方站点发布的 SVG 路径（无弧命令），逐点照搬。
//  · 其余十枚拿不到可用的官方路径，改用 CodeIsland 的 cli-icons/<tool>.png 轮廓化：
//    纯 Python 从 PNG 里按配色分离出前景字形（剥掉磁贴底、去掉贴边辉光与噪点碎块），
//    再沿线扫描出闭合环（洞作为反向环，配合 even-odd 填充）、Douglas-Peucker 简化，
//    坐标即 PNG 像素坐标。Qoder 虽有一份官方 SVG，但其字形与 PNG 里的不同（IoU 0.35），
//    按「以 CodeIsland 的资产为准」的判据仍走轮廓化。
//  · 每枚都与来源 PNG 的字形剪影做过 IoU 对照（见各条注释），探针脚本在
//    /tmp/agent-marks-probe（不进仓库）。
//
//  填充规则：even-odd。轮廓化时洞本来就是独立子路径；官方路径里的挖空同理，
//  这条规则已被逐枚渲染比对过。
//

